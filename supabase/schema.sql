        perform jct_private.quest_progress(p_sender, 'wq_social', 1, 'weekly');
        perform jct_private.quest_progress(s.username, 'wq_social', 1, 'weekly');
        perform jct_private.quest_progress(p_sender, 'mq_guide', jct_private.friend_count(p_sender), 'monthly', 'max');
        perform jct_private.quest_progress(s.username, 'mq_guide', jct_private.friend_count(s.username), 'monthly', 'max');
    else
        delete from public.friend_requests where sender_username = p_sender and receiver_username = s.username;
    end if;
    return jsonb_build_object('success', true);
end $$;

