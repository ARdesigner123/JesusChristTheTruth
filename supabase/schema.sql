create or replace function public.jct_leaderboard(p_category text default 'time', p_period text default 'daily')
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    v_col text;
    v_users jsonb;
begin
    perform jct_private.process_resets();
    v_col := case
        when p_category = 'holypower' then 'holypower'
        when p_category = 'quizzes' then 'quizzes_passed'
        when p_category = 'quests' then 'quests_done'
        when p_category = 'streak' then 'daily_streak'
        when p_category = 'xp' then 'xp'
        when p_period = 'daily' then 'active_time_daily'
        when p_period = 'weekly' then 'active_time_weekly'
        when p_period = 'monthly' then 'active_time_monthly'
        else 'active_time' end;

    execute format($q$
        select coalesce(jsonb_agg(jsonb_build_object(
                 'username', username, %L, coalesce(%I, 0), 'xp', coalesce(xp, 0),
                 'avatar_url', coalesce(avatar_url, 'static/image/defaultAvatar.jpg'),
                 'avatar_frame', coalesce(avatar_frame, 'shape-arch'),
                 'avatar_color', coalesce(avatar_color, 'color-gold'),
                 'avatar_effect', coalesce(avatar_effect, 'effect-none'))), '[]'::jsonb)
          from (select * from public.users order by coalesce(%I, 0) desc, username limit 50) t
    $q$, v_col, v_col, v_col) into v_users;

    return jsonb_build_object(
        'users', v_users,
        'sortCol', v_col,
        'totalUsers', (select count(*) from public.users),
        'timers', (select jsonb_build_object('daily_reset', daily_reset, 'weekly_reset', weekly_reset,
                                              'monthly_reset', monthly_reset)
                     from public.server_timers where id = 1));
end $$;

-- ---------------- QUIZ ----------------
create or replace function public.jct_submit_quiz(p_token text, p_status text, p_mode text, p_correct int, p_time int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    s record;
    u public.users%rowtype;
    v_rec public.quiz_leaderboards%rowtype;
    v_new boolean := false;
    v_hp bigint := 0;
    v_xp bigint := 0;
    v_today date := jct_private.sg_today();
begin
    select * into s from jct_private.require_session(p_token, false);
    if p_mode not in ('daily','easy','medium','hard','difficult','extreme','insane','impossible') then
        perform jct_private.fail('Unknown quiz mode.');
    end if;
    if p_status not in ('pass','fail') then perform jct_private.fail('Invalid quiz status.'); end if;
    p_correct := greatest(0, least(coalesce(p_correct, 0), 20));
    p_time := greatest(0, coalesce(p_time, 0));

    select * into u from public.users where id = s.user_id for update;
    if p_mode = 'daily' and left(u.last_quiz_date::text, 10) = v_today::text then
        perform jct_private.fail('You have already taken today''s Daily Quiz.');
    end if;

    select * into v_rec from public.quiz_leaderboards where username = u.username and mode = p_mode
     order by correct_count desc, time_taken asc limit 1;
    if not found then
        v_new := true;
        insert into public.quiz_leaderboards(username, mode, correct_count, time_taken, status)
        values (u.username, p_mode, p_correct, p_time, p_status);
    elsif p_correct > coalesce(v_rec.correct_count, 0)
       or (p_correct = coalesce(v_rec.correct_count, 0) and p_time < coalesce(v_rec.time_taken, 2147483647)) then
        v_new := true;
        update public.quiz_leaderboards set correct_count = p_correct, time_taken = p_time, status = p_status
         where username = u.username and mode = p_mode;
    end if;

    if p_status = 'pass' then
        select x.hp, x.xp into v_hp, v_xp from (values
            ('daily', 1000, 500), ('easy', 200, 200), ('medium', 300, 500), ('hard', 500, 1000),
            ('difficult', 800, 2500), ('extreme', 1400, 5000), ('insane', 2000, 8000), ('impossible', 4000, 14000)
        ) as x(mode, hp, xp) where x.mode = p_mode;
    end if;

    update public.users set
        quizzes_attempted = coalesce(quizzes_attempted, 0) + 1,
        quizzes_passed = coalesce(quizzes_passed, 0) + case when p_status = 'pass' then 1 else 0 end,
        quizzes_failed = coalesce(quizzes_failed, 0) + case when p_status = 'fail' then 1 else 0 end,
        holypower = coalesce(holypower, 0) + v_hp,
        xp = coalesce(xp, 0) + v_xp
    where id = u.id;
    if p_mode = 'daily' then
        update public.users set last_quiz_date = v_today where id = u.id;
    end if;

    if p_mode = 'daily' then
        perform jct_private.quest_progress(u.username, 'dq_devotion', 1, 'daily');
    end if;
    if p_status = 'pass' then
        perform jct_private.quest_progress(u.username, 'wq_scholar', 1, 'weekly');
        perform jct_private.quest_progress(u.username, 'mq_devotion', 1, 'monthly');
        case p_mode
            when 'easy' then perform jct_private.quest_progress(u.username, 'dq_step', 1, 'daily');
            when 'medium' then perform jct_private.quest_progress(u.username, 'dq_scholar', 1, 'daily');
            when 'hard' then
                perform jct_private.quest_progress(u.username, 'wq_knowledge', 1, 'weekly');
                perform jct_private.quest_progress(u.username, 'mq_theologian', 1, 'monthly');
            when 'difficult' then perform jct_private.quest_progress(u.username, 'wq_trial_fire', 1, 'weekly');
            when 'extreme' then perform jct_private.quest_progress(u.username, 'wq_extreme_faith', 1, 'weekly');
            when 'daily' then perform jct_private.quest_progress(u.username, 'wq_daily_quiz_4', 1, 'weekly');
            else null;
        end case;
        if v_hp > 0 then
            perform jct_private.quest_progress(u.username, 'wq_consecration', v_hp, 'weekly');
        end if;
        perform jct_private.check_rank_quests(u.username);
    end if;

