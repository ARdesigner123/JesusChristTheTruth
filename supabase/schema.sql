-- ---------------------------------------------------------------------
-- LOCK DOWN: RLS on, no policies, no direct grants for the API roles.
-- All access goes through the SECURITY DEFINER functions below.
-- ---------------------------------------------------------------------
do $$
declare
    t text;
    p record;
    app_tables text[] := array[
        'users','guests','jct_sessions','jct_config','presence','server_timers',
        'quiz_leaderboards','user_daily_quests','user_weekly_quests','user_monthly_quests',
        'friends','friend_requests','friend_messages','topics','responses','comments',
        'testimonies','post_reactions','chat_sessions','chat_messages'];
begin
    foreach t in array app_tables loop
        execute format('alter table public.%I enable row level security', t);
        for p in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
            execute format('drop policy %I on public.%I', p.policyname, t);
        end loop;
        if exists (select 1 from pg_roles where rolname = 'anon') then
            execute format('revoke all on public.%I from anon', t);
        end if;
        if exists (select 1 from pg_roles where rolname = 'authenticated') then
            execute format('revoke all on public.%I from authenticated', t);
        end if;
    end loop;
end $$;

