-- ---------------- ACTIVE TIME / PROFILE ----------------
create or replace function public.jct_sync_time(p_token text, p_seconds int default 0)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    s record;
    u public.users%rowtype;
    v_credit int;
    v_total bigint;
    v_step int;
    v_hp bigint;
    v_xp bigint;
    v_hp_before bigint;
    ms record;
    v_today date := jct_private.sg_today();
    v_streak int;
    v_new_day boolean := false;
begin
    select * into s from jct_private.require_session(p_token);
    perform jct_private.process_resets();

    if s.is_guest then
        select jct_private.credit_seconds(p_seconds, last_time_sync) into v_credit from public.guests where name = s.username;
        update public.guests
           set active_time = coalesce(active_time, 0) + coalesce(v_credit, 0),
               last_time_sync = case when p_seconds > 0 then now() else last_time_sync end
         where name = s.username
        returning active_time into v_total;
        return jsonb_build_object('username', s.username, 'is_guest', true, 'total_time', coalesce(v_total, 0));
    end if;

    select * into u from public.users where id = s.user_id for update;
    v_credit := jct_private.credit_seconds(p_seconds, u.last_time_sync);
    v_total := coalesce(u.active_time, 0) + v_credit;
    v_step := coalesce(u.milestone_step, 0);
    v_hp_before := coalesce(u.holypower, 0);
    v_hp := v_hp_before;
    v_xp := coalesce(u.xp, 0);

    select * into ms from jct_private.milestone(v_step);
    while v_total >= ms.m loop
        v_hp := v_hp + ms.r;
        v_xp := v_xp + ms.x;
        v_step := v_step + 1;
        select * into ms from jct_private.milestone(v_step);
    end loop;

    v_streak := coalesce(u.daily_streak, 0);
    if v_credit > 0 and coalesce(left(u.last_active_date::text, 10), '') <> v_today::text then
        v_new_day := true;
        if left(u.last_active_date::text, 10) = (v_today - 1)::text then
            v_streak := v_streak + 1;
        else
            v_streak := 1;
        end if;
    end if;

    update public.users set
        active_time = v_total,
        active_time_daily = coalesce(active_time_daily, 0) + v_credit,
        active_time_weekly = coalesce(active_time_weekly, 0) + v_credit,
        active_time_monthly = coalesce(active_time_monthly, 0) + v_credit,
        holypower = v_hp,
        xp = v_xp,
        milestone_step = v_step,
        daily_streak = v_streak,
        last_time_sync = case when p_seconds > 0 then now() else last_time_sync end
    where id = u.id;
    if v_new_day then
        -- separate statement: legacy databases may store this column as text
        update public.users set last_active_date = v_today where id = u.id;
    end if;

    if v_credit > 0 then
        perform jct_private.quest_progress(u.username, 'dq_pilgrim', v_credit / 60.0, 'daily');
        perform jct_private.quest_progress(u.username, 'wq_sabbath', v_credit / 60.0, 'weekly');
        perform jct_private.quest_progress(u.username, 'mq_pilgrimage', v_credit / 3600.0, 'monthly');
    end if;
    if v_new_day then
        perform jct_private.quest_progress(u.username, 'wq_steadfast', v_streak, 'weekly', 'max');
        perform jct_private.quest_progress(u.username, 'mq_true_believer', v_streak, 'monthly', 'max');
    end if;
    if v_hp > v_hp_before then
        perform jct_private.quest_progress(u.username, 'wq_consecration', v_hp - v_hp_before, 'weekly');
    end if;
    perform jct_private.check_rank_quests(u.username);

    return jct_private.user_payload(u.username);
end $$;

