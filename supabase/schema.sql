-- ---------------- AUTH ----------------
create or replace function public.jct_register(p_username text, p_password text, p_country text default null)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare
    v_err text;
    v_id uuid;
begin
    p_username := trim(p_username);
    v_err := jct_private.validate_username(p_username);
    if v_err is not null then perform jct_private.fail(v_err); end if;
    v_err := jct_private.validate_password(p_password);
    if v_err is not null then perform jct_private.fail(v_err); end if;
    if exists (select 1 from public.users where lower(username) = lower(p_username)) then
        perform jct_private.fail('Username is already taken.');
    end if;

    insert into public.users(username, password_hash, country, active_time)
    values (p_username, extensions.crypt(p_password, extensions.gen_salt('bf', 10)),
            left(coalesce(p_country, 'Unknown'), 80), 0)
    returning id into v_id;

    return jsonb_build_object('token', jct_private.new_session(v_id, null), 'username', p_username, 'is_guest', false);
end $$;

create or replace function public.jct_login(p_username text, p_password text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare
    u public.users%rowtype;
    v_hash text;
begin
    select * into u from public.users where username = trim(p_username);
    if not found then
        perform jct_private.fail('User not found. Please register first.');
    end if;
    v_hash := u.password_hash;
    -- Node's bcrypt writes $2b$ hashes; pgcrypto understands the identical $2a$ form.
    if v_hash like '$2b$%' or v_hash like '$2y$%' then
        v_hash := '$2a$' || substr(v_hash, 5);
    end if;
    if v_hash is null or extensions.crypt(coalesce(p_password, ''), v_hash) <> v_hash then
        perform jct_private.fail('Incorrect username or password.');
    end if;
    return jsonb_build_object('token', jct_private.new_session(u.id, null), 'username', u.username,
                              'is_guest', false, 'is_admin', u.id = jct_private.owner_id());
end $$;

