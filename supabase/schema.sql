create or replace function public.jct_add_post(p_token text, p_table text, p_content text, p_parent_id text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    s record;
    v_type text;
begin
    select * into s from jct_private.require_session(p_token);
    p_content := trim(coalesce(p_content, ''));
    if p_content = '' or p_content = '<br>' then perform jct_private.fail('Content cannot be empty.'); end if;
    if length(p_content) > 20000 then perform jct_private.fail('That post is too long.'); end if;
    v_type := case when s.is_admin then 'admin' when s.is_guest then 'guest' else 'user' end;

    if p_table = 'topics' then
        insert into public.topics(title, author_name, author_type) values (p_content, s.display_name, v_type);
        if not s.is_guest then perform jct_private.quest_progress(s.username, 'dq_add_topic', 1, 'daily'); end if;
    elsif p_table = 'testimonies' then
        insert into public.testimonies(content, author_name, author_type) values (p_content, s.display_name, v_type);
        if not s.is_guest then perform jct_private.quest_progress(s.username, 'dq_add_testimony', 1, 'daily'); end if;
    elsif p_table = 'responses' then
        if not exists (select 1 from public.topics where id::text = p_parent_id) then perform jct_private.fail('Topic not found.'); end if;
        execute 'insert into public.responses(topic_id, content, author_name, author_type)
                 select id, $1, $2, $3 from public.topics where id::text = $4'
            using p_content, s.display_name, v_type, p_parent_id;
    elsif p_table = 'comments' then
        if not exists (select 1 from public.responses where id::text = p_parent_id) then perform jct_private.fail('Response not found.'); end if;
        execute 'insert into public.comments(response_id, content, author_name, author_type)
                 select id, $1, $2, $3 from public.responses where id::text = $4'
            using p_content, s.display_name, v_type, p_parent_id;
    else
        perform jct_private.fail('Unknown post type.');
    end if;
    return jsonb_build_object('success', true);
end $$;

create or replace function public.jct_edit_post(p_token text, p_table text, p_id text, p_content text)
