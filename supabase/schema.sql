create or replace function jct_private.reward_top3(p_col text, p_rewards bigint[], p_period text) returns void
language plpgsql security definer set search_path = public as $$
declare
    r record;
    i int := 0;
begin
    for r in execute format('select username from public.users where coalesce(%I,0) > 0 order by %I desc limit 3', p_col, p_col) loop
        i := i + 1;
        update public.users
           set holypower = coalesce(holypower, 0) + p_rewards[i],
               xp = coalesce(xp, 0) + p_rewards[i]
         where username = r.username;
        if p_period = 'monthly' then
            perform jct_private.quest_progress(r.username, 'mq_saintly', 1, 'monthly', 'max');
        end if;
    end loop;
end $$;

create or replace function jct_private.process_resets() returns void
language plpgsql security definer set search_path = public as $$
declare
    t record;
    v_now bigint := jct_private.now_ms();
begin
    select id, daily_reset::numeric as d, weekly_reset::numeric as w, monthly_reset::numeric as m
      into t from public.server_timers where id = 1 for update;
    if not found then
        insert into public.server_timers(id, daily_reset, weekly_reset, monthly_reset)
        values (1, jct_private.next_reset('daily'), jct_private.next_reset('weekly'), jct_private.next_reset('monthly'))
        on conflict (id) do nothing;
        return;
    end if;

    if t.d is null or v_now >= t.d then
        perform jct_private.reward_top3('active_time_daily', array[200,100,50]::bigint[], 'daily');
        update public.users set active_time_daily = 0 where coalesce(active_time_daily, 0) <> 0;
        update public.server_timers set daily_reset = jct_private.next_reset('daily') where id = 1;
    end if;
    if t.w is null or v_now >= t.w then
        perform jct_private.reward_top3('active_time_weekly', array[2000,1500,1000]::bigint[], 'weekly');
        update public.users set active_time_weekly = 0 where coalesce(active_time_weekly, 0) <> 0;
        update public.server_timers set weekly_reset = jct_private.next_reset('weekly') where id = 1;
    end if;
    if t.m is null or v_now >= t.m then
        perform jct_private.reward_top3('active_time_monthly', array[15000,10000,7500]::bigint[], 'monthly');
        update public.users set active_time_monthly = 0 where coalesce(active_time_monthly, 0) <> 0;
        update public.server_timers set monthly_reset = jct_private.next_reset('monthly') where id = 1;
    end if;
end $$;

-- How many seconds of a client's claim we accept (prevents inflated time).
create or replace function jct_private.credit_seconds(p_claim int, p_last timestamptz) returns int
language plpgsql stable as $$
declare v_allowed int;
begin
    if p_claim is null or p_claim <= 0 then return 0; end if;
    if p_last is null then v_allowed := 30;
    else v_allowed := greatest(0, extract(epoch from (now() - p_last))::int) + 5;
    end if;
    return least(p_claim, v_allowed, 900);
end $$;

create or replace function jct_private.user_payload(p_username text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    u public.users%rowtype;
    nm record;
    v_prev bigint := 0;
begin
    select * into u from public.users where username = p_username;
    if not found then return null; end if;
    select * into nm from jct_private.milestone(coalesce(u.milestone_step, 0));
    if coalesce(u.milestone_step, 0) > 0 then
        select m into v_prev from jct_private.milestone(u.milestone_step - 1);
    end if;
    return jsonb_build_object(
        'username', u.username,
        'is_guest', false,
        'is_admin', u.id = jct_private.owner_id(),
        'country', u.country,
        'total_time', coalesce(u.active_time, 0),
        'active_time_daily', coalesce(u.active_time_daily, 0),
        'active_time_weekly', coalesce(u.active_time_weekly, 0),
        'active_time_monthly', coalesce(u.active_time_monthly, 0),
        'holypower', coalesce(u.holypower, 0),
        'xp', coalesce(u.xp, 0),
        'daily_streak', coalesce(u.daily_streak, 0),
        'next_milestone', nm.m,
        'next_reward', nm.r,
        'next_xp', nm.x,
        'prev_milestone', coalesce(v_prev, 0),
        'quizzes_passed', coalesce(u.quizzes_passed, 0),
        'quizzes_attempted', coalesce(u.quizzes_attempted, 0),
        'quizzes_failed', coalesce(u.quizzes_failed, 0),
        'quests_done', coalesce(u.quests_done, 0),
        'last_quiz_date', left(u.last_quiz_date::text, 10),
        'today', jct_private.sg_today()::text,
        'avatar_url', coalesce(u.avatar_url, 'static/image/defaultAvatar.jpg'),
        'avatar_frame', coalesce(u.avatar_frame, 'shape-arch'),
        'avatar_color', coalesce(u.avatar_color, 'color-gold'),
        'avatar_effect', coalesce(u.avatar_effect, 'effect-none'),
        'friends_count', (select count(*) from public.friends f where f.user1 = u.username or f.user2 = u.username),
        'created_at', u.created_at
    );
end $$;

