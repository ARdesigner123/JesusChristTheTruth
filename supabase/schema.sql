    update public.quiz_leaderboards set username = p_new_username where username = v_old;
    update public.user_daily_quests set username = p_new_username where username = v_old;
    update public.user_weekly_quests set username = p_new_username where username = v_old;
    update public.user_monthly_quests set username = p_new_username where username = v_old;
    update public.friends set user1 = p_new_username where user1 = v_old;
    update public.friends set user2 = p_new_username where user2 = v_old;
    update public.friend_requests set sender_username = p_new_username where sender_username = v_old;
    update public.friend_requests set receiver_username = p_new_username where receiver_username = v_old;
