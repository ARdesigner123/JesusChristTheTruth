    elsif p_table = 'responses' then
        delete from public.comments where response_id::text = p_id;
    end if;
    execute format('delete from public.%I where id::text = $1', p_table) using p_id;
    delete from public.post_reactions where post_table = p_table and post_id = p_id;
    return jsonb_build_object('success', true);
end $$;

create or replace function public.jct_react(p_token text, p_table text, p_id text, p_kind text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    s record;
    v_col text;
    v_delta int;
    v_count int;
begin
    select * into s from jct_private.require_session(p_token);
    if p_table not in ('topics','responses','comments','testimonies') then perform jct_private.fail('Unknown post type.'); end if;
    v_col := case p_kind when 'like' then 'likes_count' when 'favorite' then 'favorites_count' end;
    if v_col is null then perform jct_private.fail('Unknown reaction.'); end if;

    delete from public.post_reactions where username = s.username and post_table = p_table and post_id = p_id and kind = p_kind;
    if found then
        v_delta := -1;
    else
        insert into public.post_reactions(username, post_table, post_id, kind) values (s.username, p_table, p_id, p_kind);
        v_delta := 1;
    end if;
    execute format('update public.%I set %I = greatest(coalesce(%I, 0) + $1, 0) where id::text = $2 returning %I',
                   p_table, v_col, v_col, v_col)
        into v_count using v_delta, p_id;
    if v_count is null then perform jct_private.fail('Post not found.'); end if;
    if v_delta > 0 and not s.is_guest then
        perform jct_private.quest_progress(s.username, 'dq_like_post', 1, 'daily');
    end if;
    return jsonb_build_object('active', v_delta > 0, 'count', v_count);
end $$;

