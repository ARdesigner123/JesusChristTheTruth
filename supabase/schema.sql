create or replace function public.jct_delete_post(p_token text, p_table text, p_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
    s record;
    v_author text;
begin
    select * into s from jct_private.require_session(p_token);
    if p_table not in ('topics','responses','comments','testimonies') then perform jct_private.fail('Unknown post type.'); end if;
    execute format('select author_name from public.%I where id::text = $1', p_table) into v_author using p_id;
    if v_author is null then perform jct_private.fail('Post not found.'); end if;
    if v_author <> s.display_name and not s.is_admin then
        perform jct_private.fail('You can only delete your own posts.');
