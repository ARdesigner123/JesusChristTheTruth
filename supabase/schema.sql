-- Make sure the user has a quest set for the current period; returns it.
create or replace function jct_private.ensure_quests(p_username text, p_period text,
    out assigned jsonb, out progress jsonb, out assigned_date text)
language plpgsql security definer set search_path = public as $$
declare
    tbl text := jct_private.quest_table(p_period);
    v_ident date := (to_timestamp(jct_private.next_reset(p_period) / 1000.0) at time zone 'UTC')::date;
    v_found boolean;
begin
    execute format('select assigned_quests, progress, last_assigned_date::text from public.%I where username = $1', tbl)
        into assigned, progress, assigned_date using p_username;
    v_found := assigned_date is not null or assigned is not null;

    if assigned_date is distinct from v_ident::text or assigned is null or jsonb_typeof(assigned) <> 'array' then
        if p_period = 'monthly' then
            assigned := jct_private.quest_pool('monthly');
        else
            select coalesce(jsonb_agg(q), '[]'::jsonb) into assigned
            from (select q from jsonb_array_elements(jct_private.quest_pool(p_period)) q order by random() limit 4) s;
        end if;
        progress := '{}'::jsonb;
        assigned_date := v_ident::text;
        if v_found then
            execute format('update public.%I set last_assigned_date = $2, assigned_quests = $3, progress = $4 where username = $1', tbl)
                using p_username, v_ident, assigned, progress;
        else
            execute format('insert into public.%I(username, last_assigned_date, assigned_quests, progress) values ($1,$2,$3,$4)', tbl)
                using p_username, v_ident, assigned, progress;
        end if;
    end if;
    progress := coalesce(progress, '{}'::jsonb);
end $$;

-- Add progress to a quest (p_mode 'add') or raise it to a value (p_mode 'max').
create or replace function jct_private.quest_progress(p_username text, p_quest_id text, p_amount numeric,
    p_period text default 'daily', p_mode text default 'add') returns boolean
language plpgsql security definer set search_path = public as $$
declare
    q record;
    v_def jsonb;
    v_cur numeric;
    v_max numeric;
    v_new numeric;
    v_hp bigint;
    v_xp bigint;
    v_done boolean := false;
begin
    if p_username is null or p_amount is null or p_amount <= 0 then return false; end if;
    if not exists (select 1 from public.users where username = p_username) then return false; end if;

    select * into q from jct_private.ensure_quests(p_username, p_period);
    select e into v_def from jsonb_array_elements(q.assigned) e where e->>'id' = p_quest_id limit 1;
    if v_def is null then return false; end if;

    v_cur := coalesce((q.progress->>p_quest_id)::numeric, 0);
    v_max := (v_def->>'max')::numeric;
    if v_cur >= v_max then return false; end if;

    v_new := case when p_mode = 'max' then greatest(v_cur, p_amount) else v_cur + p_amount end;
    if v_new >= v_max then
        v_new := v_max;
        v_done := true;
    end if;
    v_new := round(v_new, 3);

    execute format('update public.%I set progress = jsonb_set(coalesce(progress, ''{}''::jsonb), array[$2], to_jsonb($3::numeric)) where username = $1',
                   jct_private.quest_table(p_period))
        using p_username, p_quest_id, v_new;

    if v_done then
        v_hp := coalesce((v_def->>'rewardHP')::bigint, 0);
        v_xp := coalesce((v_def->>'rewardXP')::bigint, 0);
        update public.users
           set holypower = coalesce(holypower, 0) + v_hp,
               xp = coalesce(xp, 0) + v_xp,
               quests_done = coalesce(quests_done, 0) + 1
         where username = p_username;
        if v_hp > 0 and p_quest_id <> 'wq_consecration' then
            perform jct_private.quest_progress(p_username, 'wq_consecration', v_hp, 'weekly');
        end if;
        if p_period = 'daily' then
            perform jct_private.quest_progress(p_username, 'wq_daily_quests_12', 1, 'weekly');
        end if;
        perform jct_private.check_rank_quests(p_username);
    end if;
    return v_done;
end $$;

create or replace function jct_private.check_rank_quests(p_username text) returns void
language plpgsql security definer set search_path = public as $$
declare v_xp bigint;
begin
    select coalesce(xp, 0) into v_xp from public.users where username = p_username;
    if v_xp >= 500 then
        perform jct_private.quest_progress(p_username, 'mq_exalted', 1, 'monthly', 'max');
    end if;
end $$;

