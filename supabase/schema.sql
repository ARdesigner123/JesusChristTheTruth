create or replace function jct_private.fail(p_msg text) returns void
language plpgsql as $$
begin
    raise exception '%', p_msg using errcode = 'P0001';
end $$;

create or replace function jct_private.owner_id() returns uuid
language sql stable security definer set search_path = public as $$
    select nullif(value, '')::uuid from public.jct_config where key = 'owner_id'
$$;

create or replace function jct_private.sg_today() returns date
language sql stable as $$
    select (now() at time zone 'Asia/Singapore')::date
$$;

create or replace function jct_private.now_ms() returns bigint
language sql volatile as $$
    select (extract(epoch from clock_timestamp()) * 1000)::bigint
$$;

-- End of the current day / week (Sunday) / month in Singapore time, as epoch ms.
create or replace function jct_private.next_reset(p_period text) returns bigint
language plpgsql stable as $$
declare
    d date := jct_private.sg_today();
    target timestamp;
begin
    if p_period = 'weekly' then
        target := (d + ((7 - extract(isodow from d)::int) % 7))::timestamp + interval '1 day' - interval '1 millisecond';
    elsif p_period = 'monthly' then
        target := date_trunc('month', d::timestamp) + interval '1 month' - interval '1 millisecond';
    else
        target := d::timestamp + interval '1 day' - interval '1 millisecond';
    end if;
    return (extract(epoch from (target at time zone 'Asia/Singapore')) * 1000)::bigint;
end $$;

-- Resolve a session token -> who is calling.
create or replace function jct_private.session_info(p_token text,
    out user_id uuid, out username text, out is_guest boolean, out is_admin boolean, out display_name text)
language plpgsql stable security definer set search_path = public as $$
declare
    s public.jct_sessions%rowtype;
begin
    if p_token is null or p_token = '' then return; end if;
    select * into s from public.jct_sessions where token = p_token and expires_at > now();
    if not found then return; end if;
    if s.user_id is not null then
        select u.id, u.username into user_id, username from public.users u where u.id = s.user_id;
        if username is null then return; end if;
        is_guest := false;
        is_admin := (user_id = jct_private.owner_id());
    else
        username := s.guest_name;
        is_guest := true;
        is_admin := false;
    end if;
    display_name := case when is_admin then 'Admin / Owner' else username end;
end $$;

create or replace function jct_private.require_session(p_token text, p_allow_guest boolean default true,
    out user_id uuid, out username text, out is_guest boolean, out is_admin boolean, out display_name text)
language plpgsql stable security definer set search_path = public as $$
begin
    select * into user_id, username, is_guest, is_admin, display_name from jct_private.session_info(p_token);
    if username is null then
        perform jct_private.fail('Your session has expired. Please log in again.');
    end if;
    if is_guest and not p_allow_guest then
        perform jct_private.fail('Please register an account to use this feature.');
    end if;
end $$;

create or replace function jct_private.new_session(p_user_id uuid, p_guest_name text) returns text
language plpgsql security definer set search_path = public, extensions as $$
declare
    v_token text := encode(extensions.gen_random_bytes(32), 'hex');
begin
    delete from public.jct_sessions where expires_at < now();
    insert into public.jct_sessions(token, user_id, guest_name, expires_at)
    values (v_token, p_user_id, p_guest_name,
            now() + case when p_user_id is null then interval '365 days' else interval '90 days' end);
    return v_token;
end $$;

create or replace function jct_private.validate_username(p text) returns text
language plpgsql immutable as $$
begin
    if p is null or length(p) < 8 or length(p) > 20 then return 'Username must be 8 to 20 characters.'; end if;
    if p !~ '^[A-Za-z0-9]' then return 'Username cannot start with a special character.'; end if;
    if p !~ '^[A-Za-z0-9_.-]+$' then return 'Username may only contain letters, numbers, _ . and -'; end if;
    if p !~ '[A-Z]' then return 'Username must contain at least one uppercase letter.'; end if;
    if p !~ '[a-z]' then return 'Username must contain at least one lowercase letter.'; end if;
    if p !~ '[0-9]' then return 'Username must contain at least one number.'; end if;
    if lower(p) like 'guest\_%' then return 'Usernames starting with "Guest_" are reserved.'; end if;
    return null;
end $$;

create or replace function jct_private.validate_password(p text) returns text
language plpgsql immutable as $$
begin
    if p is null or length(p) < 8 or length(p) > 30 then return 'Password must be 8 to 30 characters.'; end if;
    if p !~ '^[A-Za-z0-9]' then return 'Password cannot start with a special character.'; end if;
    if p !~ '[A-Z]' then return 'Password must contain at least one uppercase letter.'; end if;
    if p !~ '[a-z]' then return 'Password must contain at least one lowercase letter.'; end if;
    if p !~ '[0-9]' then return 'Password must contain at least one number.'; end if;
    if p !~ '[^A-Za-z0-9]' then return 'Password must contain at least one special character.'; end if;
    return null;
end $$;

-- Active-time milestone ladder (same numbers as the old server).
create or replace function jct_private.milestone(p_step int, out m bigint, out r bigint, out x bigint)
language plpgsql immutable as $$
declare
    base_m bigint[] := array[100,400,700,1000,1600,2500,3500,5000,8000,15000,24000,40000];
    base_r bigint[] := array[5,15,30,50,70,100,140,180,300,500,750,1000];
    base_x bigint[] := array[10,30,60,100,130,170,210,240,300,500,800,1400];
    i int;
begin
    if p_step < 12 then
        m := base_m[p_step + 1]; r := base_r[p_step + 1]; x := base_x[p_step + 1];
        return;
    end if;
    m := 40000; r := 1000; x := 1400;
    for i in 1..(p_step - 12 + 1) loop
        m := ceil(m * 1.2); r := ceil(r * 1.2); x := ceil(x * 1.2);
    end loop;
end $$;

