create or replace function public.jct_send_friend_request(p_token text, p_receiver text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare s record;
begin
    select * into s from jct_private.require_session(p_token, false);
    if p_receiver = s.username then perform jct_private.fail('You cannot add yourself.'); end if;
    if not exists (select 1 from public.users where username = p_receiver) then
        perform jct_private.fail('User not found.');
    end if;
    if jct_private.are_friends(s.username, p_receiver) then
        perform jct_private.fail('You are already friends.');
    end if;
    if exists (select 1 from public.friend_requests
                where (sender_username = s.username and receiver_username = p_receiver)
                   or (sender_username = p_receiver and receiver_username = s.username)) then
        perform jct_private.fail('Request already exists.');
    end if;
    insert into public.friend_requests(sender_username, receiver_username, status)
    values (s.username, p_receiver, 'pending');
    perform jct_private.quest_progress(s.username, 'dq_fellowship', 1, 'daily');
    return jsonb_build_object('message', 'Request sent!');
end $$;

